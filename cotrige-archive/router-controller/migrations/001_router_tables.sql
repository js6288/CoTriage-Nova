CREATE TABLE IF NOT EXISTS router_decisions (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  event_id VARCHAR(128) NOT NULL,
  trace_id VARCHAR(128) NULL,
  schema_version VARCHAR(32) NULL,
  source VARCHAR(255) NULL,
  equipment VARCHAR(255) NULL,
  event_ts DATETIME(6) NULL,
  inferred_at DATETIME(6) NULL,
  template_id VARCHAR(128) NULL,
  raw_log_hash VARCHAR(64) NULL,
  edge_pred VARCHAR(64) NULL,
  severity INT NULL,
  confidence DOUBLE NULL,
  edge_uncertainty DOUBLE NULL,
  inference_path VARCHAR(64) NULL,
  model_version VARCHAR(128) NULL,
  rule_version VARCHAR(128) NULL,
  action VARCHAR(16) NOT NULL,
  reason VARCHAR(128) NULL,
  policy_ref VARCHAR(128) NULL,
  score DOUBLE NULL,
  threshold DOUBLE NULL,
  cloud_health VARCHAR(32) NULL,
  raise_version VARCHAR(64) NULL,
  latency_ms BIGINT NULL,
  routed_at DATETIME(6) NOT NULL,
  created_at DATETIME(6) NULL,
  updated_at DATETIME(6) NULL,
  UNIQUE KEY uk_router_decisions_event_id (event_id),
  KEY idx_router_decisions_routed_at (routed_at),
  KEY idx_router_decisions_action_routed_at (action, routed_at),
  KEY idx_router_decisions_template_routed_at (template_id, routed_at),
  KEY idx_router_decisions_source_routed_at (source, routed_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS router_state_snapshots (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  snapshot_type VARCHAR(64) NOT NULL,
  snapshot_key VARCHAR(255) NOT NULL,
  payload_json LONGTEXT NOT NULL,
  version VARCHAR(128) NULL,
  checksum VARCHAR(128) NULL,
  is_active BOOLEAN NULL,
  restored_at DATETIME(6) NULL,
  metadata_json TEXT NULL,
  created_at DATETIME(6) NULL,
  KEY idx_router_state_type_key_active (snapshot_type, snapshot_key, is_active),
  KEY idx_router_state_version (version),
  KEY idx_router_state_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cloud_outbox (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  event_id VARCHAR(128) NOT NULL,
  request_id VARCHAR(160) NOT NULL,
  idempotency_key VARCHAR(160) NOT NULL,
  payload_json LONGTEXT NOT NULL,
  route_decision_json TEXT NULL,
  priority_score DOUBLE NULL,
  defer_reason VARCHAR(128) NULL,
  status VARCHAR(16) NOT NULL,
  attempt INT NULL,
  max_attempts INT NULL,
  next_retry_at DATETIME(6) NULL,
  deadline_at DATETIME(6) NULL,
  created_at DATETIME(6) NULL,
  updated_at DATETIME(6) NULL,
  locked_by VARCHAR(128) NULL,
  locked_until DATETIME(6) NULL,
  sent_at DATETIME(6) NULL,
  done_at DATETIME(6) NULL,
  last_error TEXT NULL,
  last_error_at DATETIME(6) NULL,
  dlq_reason TEXT NULL,
  UNIQUE KEY uk_cloud_outbox_event_id (event_id),
  UNIQUE KEY uk_cloud_outbox_request_id (request_id),
  UNIQUE KEY uk_cloud_outbox_idempotency_key (idempotency_key),
  KEY idx_cloud_outbox_status_priority (status, priority_score),
  KEY idx_cloud_outbox_status (status),
  KEY idx_cloud_outbox_next_retry_at (next_retry_at),
  KEY idx_cloud_outbox_locked_until (locked_until),
  KEY idx_cloud_outbox_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

