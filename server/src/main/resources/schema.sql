CREATE TABLE IF NOT EXISTS `classifier_configs` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `name` varchar(255) NOT NULL,
  `endpoint` text NOT NULL,
  `model` varchar(255) NOT NULL,
  `timeout_ms` bigint NOT NULL,
  `threshold` double NOT NULL,
  `status` varchar(32) NOT NULL,
  `is_active` tinyint(1) NOT NULL,
  `config_version` bigint NOT NULL,
  `etag` varchar(255) NOT NULL,
  `created_at` datetime(3) DEFAULT NULL,
  `updated_at` datetime(3) DEFAULT NULL,
  `deleted_at` datetime(3) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_classifier_configs_name` (`name`),
  KEY `idx_classifier_configs_is_active` (`is_active`),
  KEY `idx_classifier_configs_deleted_at` (`deleted_at`),
  KEY `idx_classifier_configs_status` (`status`)
);

