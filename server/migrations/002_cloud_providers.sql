CREATE TABLE IF NOT EXISTS cloud_providers (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  provider VARCHAR(32) NOT NULL,
  endpoint TEXT NOT NULL,
  model VARCHAR(255) NOT NULL,
  api_key_env VARCHAR(255) NOT NULL,
  api_key TEXT NOT NULL,
  timeout_ms INT NOT NULL,
  max_tokens INT NOT NULL,
  temperature DOUBLE NOT NULL,
  top_p DOUBLE NOT NULL,
  seed INT NULL,
  health_path VARCHAR(255) NULL,
  response_path VARCHAR(255) NOT NULL,
  status VARCHAR(32) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT FALSE,
  config_version BIGINT NOT NULL DEFAULT 0,
  etag VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  created_by VARCHAR(255) NULL,
  updated_by VARCHAR(255) NULL,
  deleted_at DATETIME(6) NULL,
  last_publish_at DATETIME(6) NULL,
  UNIQUE KEY uk_cloud_providers_name (name),
  KEY idx_cloud_providers_status (status),
  KEY idx_cloud_providers_active (is_active),
  KEY idx_cloud_providers_deleted (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
